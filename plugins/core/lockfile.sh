#!/bin/bash

# Potions Plugin Lockfile Management
# Handles Potionfile.lock creation, reading, and verification

# Guard against multiple inclusion
if [ -n "$LOCKFILE_SOURCED" ] && declare -F lockfile_get >/dev/null; then
  return 0
fi
LOCKFILE_SOURCED=1

# Source core accessories if not already sourced
CORE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PLUGINS_DIR="$(dirname "$CORE_DIR")"
REPO_ROOT="$(dirname "$PLUGINS_DIR")"

if [ -z "$ACCESSORIES_SOURCED" ]; then
  source "$REPO_ROOT/packages/accessories.sh"
fi

# Lockfile location
LOCKFILE_PATH="${POTIONS_HOME}/Potionfile.lock"
LOCKFILE_HEADER="# Potionfile.lock - Auto-generated by Potions
# DO NOT EDIT MANUALLY
# Format: name|version|checksum|source
#
# Generated: $(date '+%Y-%m-%d %H:%M:%S')
"

# Initialize lockfile if it doesn't exist
# Usage: lockfile_init
lockfile_init() {
  if [ ! -f "$LOCKFILE_PATH" ]; then
    ensure_directory "$(dirname "$LOCKFILE_PATH")"
    echo "$LOCKFILE_HEADER" > "$LOCKFILE_PATH"
    log "Created lockfile at: $LOCKFILE_PATH"
  fi
}

# Read entire lockfile
# Usage: lockfile_read
lockfile_read() {
  if [ ! -f "$LOCKFILE_PATH" ]; then
    return 1
  fi
  
  # Return non-comment, non-empty lines
  awk '!/^#/ && NF' "$LOCKFILE_PATH"
}

# Check if plugin is in lockfile
# Usage: lockfile_has <plugin_name>
lockfile_has() {
  local plugin_name="$1"
  
  if [ ! -f "$LOCKFILE_PATH" ]; then
    return 1
  fi
  
  awk -F'|' -v name="$plugin_name" '$1 == name {found=1} END {exit !found}' "$LOCKFILE_PATH"
}

# Get plugin entry from lockfile
# Usage: lockfile_get <plugin_name>
# Returns: name|version|checksum|source
lockfile_get() {
  local plugin_name="$1"
  
  if [ ! -f "$LOCKFILE_PATH" ]; then
    return 1
  fi
  
  awk -F'|' -v name="$plugin_name" '$1 == name {print; exit}' "$LOCKFILE_PATH"
}

# Get specific field from lockfile entry
# Usage: lockfile_get_field <plugin_name> <field_number>
# Fields: 1=name, 2=version, 3=checksum, 4=source
lockfile_get_field() {
  local plugin_name="$1"
  local field_num="$2"
  
  local entry
  entry=$(lockfile_get "$plugin_name")
  
  if [ -z "$entry" ]; then
    return 1
  fi
  
  echo "$entry" | cut -d'|' -f"$field_num"
}

# Get plugin version from lockfile
# Usage: lockfile_get_version <plugin_name>
lockfile_get_version() {
  lockfile_get_field "$1" 2
}

# Get plugin checksum from lockfile
# Usage: lockfile_get_checksum <plugin_name>
lockfile_get_checksum() {
  lockfile_get_field "$1" 3
}

# Get plugin source from lockfile
# Usage: lockfile_get_source <plugin_name>
lockfile_get_source() {
  lockfile_get_field "$1" 4
}

# Add plugin to lockfile
# Usage: lockfile_add <name> <version> <checksum> <source>
lockfile_add() {
  local name="$1"
  local version="$2"
  local checksum="${3:-none}"
  local source="$4"
  
  lockfile_init
  
  # Remove existing entry if present
  if lockfile_has "$name"; then
    lockfile_remove "$name"
  fi
  
  # Add new entry
  echo "${name}|${version}|${checksum}|${source}" >> "$LOCKFILE_PATH"
  log "Added to lockfile: $name v$version"
}

# Remove plugin from lockfile
# Usage: lockfile_remove <plugin_name>
lockfile_remove() {
  local plugin_name="$1"
  
  if [ ! -f "$LOCKFILE_PATH" ]; then
    return 1
  fi
  
  if ! lockfile_has "$plugin_name"; then
    log "Plugin not found in lockfile: $plugin_name"
    return 1
  fi
  
  # Create temp file without the plugin entry
  local temp_file
  temp_file=$(mktemp)
  awk -F'|' -v name="$plugin_name" '$1 != name' "$LOCKFILE_PATH" > "$temp_file" || return 1
  mv "$temp_file" "$LOCKFILE_PATH"
  
  log "Removed from lockfile: $plugin_name"
}

# Update plugin in lockfile
# Usage: lockfile_update <name> <version> <checksum> <source>
lockfile_update() {
  local name="$1"
  local version="$2"
  local checksum="${3:-none}"
  local source="$4"
  
  lockfile_remove "$name" 2>/dev/null
  lockfile_add "$name" "$version" "$checksum" "$source"
}

# List all plugins in lockfile
# Usage: lockfile_list
lockfile_list() {
  if [ ! -f "$LOCKFILE_PATH" ]; then
    return 0
  fi
  
  lockfile_read | cut -d'|' -f1
}

# Count plugins in lockfile
# Usage: lockfile_count
lockfile_count() {
  if [ ! -f "$LOCKFILE_PATH" ]; then
    echo "0"
    return 0
  fi
  
  lockfile_read | wc -l | tr -d ' '
}

# Verify one installed record without changing its source or running plugin code.
lockfile_verify_entry() {
  local name="$1" version="$2" checksum="$3" source="$4"
  local plugin_path="$POTIONS_HOME/plugins/$name"
  if ! [[ "$name" =~ ^[a-zA-Z0-9][a-zA-Z0-9_-]*$ ]]; then
    log "Invalid plugin name in lockfile"
    return 1
  fi
  if [ ! -d "$plugin_path" ]; then
    log "Missing plugin: $name (expected at $plugin_path)"
    return 1
  fi
  case "$source" in
    local:*)
      if [ ! -L "$plugin_path" ] || [ "$(readlink "$plugin_path")" != "${source#local:}" ]; then
        log "Local plugin path differs from its record: $name"
        return 1
      fi
      ;;
    bundled:word-navigation)
      local bundle_path
      bundle_path=$(cd "$REPO_ROOT/plugins/bundled/word-navigation" && pwd -P) || return 1
      if [ "$name" != word-navigation ] || [ ! -L "$plugin_path" ] ||
         [ "$(readlink "$plugin_path")" != "$bundle_path" ]; then
        log "Bundled plugin path differs from its record: $name"
        return 1
      fi
      ;;
    github:*|registry:*)
      if [ -L "$plugin_path" ] || ! [[ "$checksum" =~ ^[a-f0-9]{40}$ ]]; then
        log "Recorded Git revision is unavailable for $name. Reinstall from its reviewed source to restore verification."
        return 1
      fi
      ;;
    *)
      log "Plugin provenance is unavailable for $name. Review and reinstall its source to restore verification."
      return 1
      ;;
  esac
  if [[ "$source" != local:* ]]; then
    local installed_version
    installed_version=$(get_plugin_version "$plugin_path" 2>/dev/null) || return 1
    if [ "$installed_version" != "$version" ]; then
      log "Version mismatch for $name: expected $version, found $installed_version"
      return 1
    fi
  fi
  if [[ "$checksum" =~ ^[a-f0-9]{40}$ ]]; then
    local installed_commit changes ignored_runtime
    installed_commit=$(git -C "$plugin_path" rev-parse HEAD 2>/dev/null) || return 1
    changes=$(git -C "$plugin_path" status --porcelain --untracked-files=all 2>/dev/null) || return 1
    # Startup and lifecycle hooks use these files even when Git ignores them.
    ignored_runtime=$(git -C "$plugin_path" ls-files --others --ignored --exclude-standard -- \
      ':(top,glob)config/*.zsh' ':(top,glob)config/*.sh' \
      ':(top)install.sh' ':(top)uninstall.sh' ':(top)activate.sh' ':(top)deactivate.sh') || return 1
    if [ "$installed_commit" != "$checksum" ] || [ -n "$changes" ] || [ -n "$ignored_runtime" ]; then
      log "Plugin differs from recorded Git revision: $name"
      return 1
    fi
  fi
}

# Verify all installed records, or only the requested installed plugin.
# Usage: lockfile_verify [plugin_name]
lockfile_verify() {
  local requested="${1:-}" errors=0 matches=0 name version checksum source
  if [ ! -f "$LOCKFILE_PATH" ]; then
    if [ -z "$requested" ]; then
      local plugin_path
      for plugin_path in "$POTIONS_HOME/plugins"/*; do
        if [ -d "$plugin_path" ] || [ -L "$plugin_path" ]; then
          log "Installed plugins have no lockfile"
          return 1
        fi
      done
      log "No plugins recorded"
      return 0
    fi
    log "No lockfile found for plugin: $requested"
    return 1
  fi
  while IFS='|' read -r name version checksum source; do
    [ -n "$name" ] || continue
    [ -z "$requested" ] || [ "$name" = "$requested" ] || continue
    matches=$((matches + 1))
    lockfile_verify_entry "$name" "$version" "$checksum" "$source" || errors=$((errors + 1))
  done < <(lockfile_read)
  if [ -z "$requested" ]; then
    local plugin_path plugin_name
    for plugin_path in "$POTIONS_HOME/plugins"/*; do
      [ -d "$plugin_path" ] || [ -L "$plugin_path" ] || continue
      plugin_name="${plugin_path##*/}"
      if ! lockfile_has "$plugin_name"; then
        log "Installed plugin has no lockfile record: $plugin_name"
        errors=$((errors + 1))
      fi
    done
  fi
  if [ -n "$requested" ] && [ "$matches" -ne 1 ]; then
    log "Expected one lockfile record for plugin: $requested"
    errors=$((errors + 1))
  fi
  if [ "$errors" -gt 0 ]; then
    log "Lockfile verification failed with $errors error(s)"
    return 1
  fi
  log "Lockfile verification passed"
}

# Generate lockfile from currently installed plugins
# Usage: lockfile_regenerate
lockfile_regenerate() {
  local plugins_dir="$POTIONS_HOME/plugins"
  local temp_file
  temp_file=$(mktemp)
  
  echo "$LOCKFILE_HEADER" > "$temp_file"
  
  if [ ! -d "$plugins_dir" ]; then
    log "No plugins directory found"
    mv "$temp_file" "$LOCKFILE_PATH"
    return 0
  fi
  
  for plugin_path in "$plugins_dir"/*/; do
    [ -d "$plugin_path" ] || continue
    
    local plugin_name
    plugin_name=$(basename "$plugin_path")
    
    # Skip if no manifest
    if [ ! -f "$plugin_path/plugin.potions.json" ]; then
      continue
    fi
    
    local version source checksum
    version=$(get_plugin_version "$plugin_path" 2>/dev/null || echo "unknown")
    
    # Determine source type
    if [ -L "$plugin_path" ]; then
      source="local:$(readlink "$plugin_path")"
      checksum="none"
    else
      source="unknown"
      checksum="none"
    fi
    
    echo "${plugin_name}|${version}|${checksum}|${source}" >> "$temp_file"
  done
  
  mv "$temp_file" "$LOCKFILE_PATH"
  log "Lockfile regenerated"
}

# Display lockfile contents in readable format
# Usage: lockfile_display
lockfile_display() {
  if [ ! -f "$LOCKFILE_PATH" ]; then
    echo "No lockfile found"
    return 1
  fi
  
  echo "Installed Plugins (from lockfile):"
  echo "=================================="
  
  while IFS='|' read -r name version checksum source; do
    [ -z "$name" ] && continue
    printf "%-25s %-10s %s\n" "$name" "v$version" "($source)"
  done < <(lockfile_read)
}

# Clean orphaned entries from lockfile
# Usage: lockfile_clean
lockfile_clean() {
  local plugins_dir="$POTIONS_HOME/plugins"
  local removed=0
  
  if [ ! -f "$LOCKFILE_PATH" ]; then
    return 0
  fi
  
  for name in $(lockfile_list); do
    if [ ! -d "$plugins_dir/$name" ]; then
      lockfile_remove "$name"
      removed=$((removed + 1))
    fi
  done
  
  if [ $removed -gt 0 ]; then
    log "Cleaned $removed orphaned entries from lockfile"
  fi
}
